// Writes messages/<locale>/index.ts, which gathers that language's message
// files (one per part of the app) into one object. Run after adding a file:
//   node scripts/messages-index.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "messages");

for (const locale of readdirSync(root, { withFileTypes: true })) {
  if (!locale.isDirectory()) continue;
  const dir = join(root, locale.name);
  const parts = readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .map((name) => name.slice(0, -".json".length))
    .sort();
  const source = [
    "// Generated by scripts/messages-index.mjs: one file per part of the app.",
    ...parts.map((part) => `import ${part} from "./${part}.json";`),
    "",
    `const messages = { ${parts.join(", ")} };`,
    "",
    "export default messages;",
    "",
  ].join("\n");
  writeFileSync(join(dir, "index.ts"), source);
}
